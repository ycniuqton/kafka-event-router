#!/usr/bin/env bash
# Writes the local-development environment to ./.local/dev.env (0600) and, when sourced, exports it.
#   deploy/dev/env.sh            # (re)write .local/dev.env
#   source deploy/dev/env.sh     # write + export into the current shell (e.g. to `go run ./cmd/api`)
# Staging-side values (router_dev DB password, Redis password) are read from CREDS_FILE; local-only secrets
# (cookie/cursor/workload/preview) are generated once into .local/dev-secrets.env.

_dev_env_sourced=0
[ "${BASH_SOURCE[0]}" != "$0" ] && _dev_env_sourced=1
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

# Generates the local-only secrets once; they never leave this machine.
dev_env_local_secrets() {
  local key
  [ -f "$DEV_SECRETS_FILE" ] && return 0
  umask 077
  for key in ROUTER_COOKIE_SECRET ROUTER_CURSOR_SECRET ROUTER_WORKLOAD_TOKEN ROUTER_PREVIEW_DIRECTIVE_SECRET; do
    printf '%s=%s\n' "$key" "$(openssl rand -hex 32)"
  done > "$DEV_SECRETS_FILE"
}

# Prints the connection settings that point at staging through the tunnel.
dev_env_backing() {
  local db_user db_name db_pw redis_pw
  db_user="$(dev_cred ROUTER_DEV_DB_USER)"; db_name="$(dev_cred ROUTER_DEV_DB_NAME)"
  db_pw="$(dev_cred ROUTER_DEV_DB_PASSWORD)"; redis_pw="$(dev_cred REDIS_PASSWORD)"
  [ -n "$db_pw" ] && [ -n "$redis_pw" ] || { echo "dev: ROUTER_DEV_DB_PASSWORD/REDIS_PASSWORD missing in $CREDS_FILE" >&2; return 1; }
  cat <<EOF
ROUTER_DATABASE_URL=postgres://${db_user:-$DEV_DB_NAME_DEFAULT}:${db_pw}@127.0.0.1:${DEV_PG_PORT}/${db_name:-$DEV_DB_NAME_DEFAULT}?sslmode=disable
ROUTER_REDIS_URL=redis://:${redis_pw}@127.0.0.1:${DEV_REDIS_PORT}/${DEV_REDIS_DB}
ROUTER_KAFKA_BOOTSTRAP=127.0.0.1:${DEV_KAFKA_PORT}
ROUTER_METRICS_BACKEND=prometheus
ROUTER_METRICS_URL=http://127.0.0.1:${DEV_PROM_PORT}
EOF
}

# Prints the settings of the local processes themselves.
dev_env_local() {
  cat <<EOF
ROUTER_ENV=local
ROUTER_LOG_LEVEL=${ROUTER_LOG_LEVEL:-info}
ROUTER_WORKSPACE_NAME=local-dev
ROUTER_PUBLIC_URL=http://localhost:${DEV_WEB_PORT}
ROUTER_AUTH_MODES=dev,api_token
ROUTER_SECRETS_PROVIDER=local
ROUTER_SECRETS_LOCAL_KEY_FILE=${DEV_LOCAL_DIR}/master.key
ROUTER_WORKLOAD_AUTH=static_token
ROUTER_CONTROL_PLANE_URL=http://127.0.0.1:${DEV_API_PORT}
ROUTER_CONTROL_PLANE_INTERNAL_URL=http://127.0.0.1:${DEV_API_INTERNAL_PORT}
ROUTER_INTERNAL_ADDR=127.0.0.1:${DEV_API_INTERNAL_PORT}
ROUTER_PREVIEW_URL=http://127.0.0.1:${DEV_PREVIEW_PORT}
ROUTER_WORKER_ID=local-$(hostname -s)
ROUTER_WORKER_ZONE=local
ROUTER_WORKER_CACHE_DIR=${DEV_LOCAL_DIR}/worker-cache
ROUTER_SANDBOX_CACHE_DIR=${DEV_LOCAL_DIR}/worker-cache/sandbox
ROUTER_PREVIEW_SALTS=control_plane
EOF
}

dev_env_write() {
  dev_prepare_dirs
  dev_env_local_secrets
  local tmp="$DEV_ENV_FILE.tmp"
  ( umask 077; { echo "# generated by deploy/dev/env.sh - do not commit"; dev_env_local; dev_env_backing; cat "$DEV_SECRETS_FILE"; } > "$tmp" ) || return 1
  mv "$tmp" "$DEV_ENV_FILE"
}

if dev_env_write; then
  if [ "$_dev_env_sourced" = 1 ]; then
    set -a; source "$DEV_ENV_FILE"; set +a
  else
    echo "env: wrote $DEV_ENV_FILE"
  fi
else
  [ "$_dev_env_sourced" = 1 ] && return 1 || exit 1
fi
