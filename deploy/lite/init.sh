#!/bin/sh
# Creates or completes the lite stack's .env from .env.example: random secrets, master key, admin account.
# Idempotent: a key that already exists is never changed; missing keys are appended. No docker needed.
# Usage: ./init.sh [--env-file PATH] [--admin-email EMAIL] [--public-url URL] [--trial] [--metrics] [--yes]
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
TEMPLATE="$SCRIPT_DIR/.env.example"
ENV_FILE="${LITE_ENV_FILE:-$SCRIPT_DIR/.env}"
ENV_FILE_MODE=600
SECRET_BYTES=32
DB_SECRET_BYTES=24
MASTER_KEY_BYTES=32
ADMIN_PASSWORD_LENGTH=20
ADMIN_PASSWORD_ALPHABET='A-HJ-NP-Za-km-z2-9'
DEFAULT_ADMIN_EMAIL="admin@example.com"
PRODUCTION_ENV="production"
TRIAL_ENV="staging"
PRODUCTION_PUBLIC_URL="https://router.example.com"
TRIAL_PUBLIC_URL="http://localhost:8088"
METRICS_PROFILE="metrics"
METRICS_READER="prometheus"
NO_METRICS_READER="null"
NO_METRICS_DETECTORS="route_error,connection_unhealthy,alert_firing"
KEY_PATTERN='^[A-Z][A-Z0-9_]*='

mode="production"
metrics="off"
admin_email=""
public_url=""
assume_yes="no"
generated_admin_password=""
appended=0

usage() {
  sed -n '2,4p' "$0" | sed 's/^# \{0,1\}//'
}

die() {
  echo "init.sh: $*" >&2
  exit 1
}

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --env-file) [ $# -ge 2 ] || die "--env-file needs a path"; ENV_FILE="$2"; shift 2 ;;
      --admin-email) [ $# -ge 2 ] || die "--admin-email needs a value"; admin_email="$2"; shift 2 ;;
      --public-url) [ $# -ge 2 ] || die "--public-url needs a value"; public_url="$2"; shift 2 ;;
      --trial) mode="trial"; shift ;;
      --metrics) metrics="on"; shift ;;
      --yes|-y) assume_yes="yes"; shift ;;
      -h|--help) usage; exit 0 ;;
      *) die "unknown argument: $1 (see --help)" ;;
    esac
  done
}

random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

random_base64() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 "$1" | tr -d '\n'
  else
    head -c "$1" /dev/urandom | base64 | tr -d '\n'
  fi
}

random_password() {
  out=""
  while [ "${#out}" -lt "$ADMIN_PASSWORD_LENGTH" ]; do
    out="$out$(head -c 64 /dev/urandom | LC_ALL=C tr -dc "$ADMIN_PASSWORD_ALPHABET")"
  done
  printf '%s' "$out" | cut -c "1-$ADMIN_PASSWORD_LENGTH"
}

has_key() {
  [ -f "$ENV_FILE" ] && grep -q "^$1=" "$ENV_FILE"
}

ask() {
  if [ "$assume_yes" = "yes" ] || [ ! -t 0 ]; then
    printf '%s' "$2"
    return 0
  fi
  printf '%s [%s]: ' "$1" "$2" >&2
  read -r answer || answer=""
  printf '%s' "${answer:-$2}"
}

mode_value() {
  if [ "$mode" = "trial" ]; then printf '%s' "$2"; else printf '%s' "$1"; fi
}

metrics_value() {
  if [ "$metrics" = "on" ]; then printf '%s' "$1"; else printf '%s' "$2"; fi
}

resolve_value() {
  case "$1" in
    POSTGRES_PASSWORD|REDIS_PASSWORD) random_hex "$DB_SECRET_BYTES" ;;
    ROUTER_CURSOR_SECRET|ROUTER_COOKIE_SECRET|ROUTER_PREVIEW_DIRECTIVE_SECRET|ROUTER_ALERTS_WEBHOOK_SIGNING_KEY)
      random_hex "$SECRET_BYTES" ;;
    ROUTER_SECRETS_MASTER_KEY) random_base64 "$MASTER_KEY_BYTES" ;;
    ROUTER_BOOTSTRAP_ADMIN_PASSWORD) printf '%s' "$generated_admin_password" ;;
    ROUTER_BOOTSTRAP_ADMIN_EMAIL) printf '%s' "$admin_email" ;;
    ROUTER_PUBLIC_URL) printf '%s' "$public_url" ;;
    ROUTER_ENV) mode_value "$PRODUCTION_ENV" "$TRIAL_ENV" ;;
    ROUTER_COOKIE_SECURE) mode_value true false ;;
    COMPOSE_PROFILES) metrics_value "$METRICS_PROFILE" "" ;;
    ROUTER_ROUTE_METRICS_READER) metrics_value "$METRICS_READER" "$NO_METRICS_READER" ;;
    ROUTER_ALERTS_ENABLED) metrics_value true false ;;
    ROUTER_MONITORING_ATTENTION_DETECTORS) metrics_value "" "$NO_METRICS_DETECTORS" ;;
    *) printf '%s' "$2" ;;
  esac
}

prepare_inputs() {
  if [ -z "$admin_email" ] && ! has_key ROUTER_BOOTSTRAP_ADMIN_EMAIL; then
    admin_email=$(ask "Admin email" "$DEFAULT_ADMIN_EMAIL")
  fi
  if [ -z "$public_url" ] && ! has_key ROUTER_PUBLIC_URL; then
    public_url=$(ask "Public URL" "$(mode_value "$PRODUCTION_PUBLIC_URL" "$TRIAL_PUBLIC_URL")")
  fi
}

prepare_admin_password() {
  if ! has_key ROUTER_BOOTSTRAP_ADMIN_PASSWORD && ! has_key ROUTER_BOOTSTRAP_ADMIN_PASSWORD_FILE; then
    generated_admin_password=$(random_password)
  fi
}

create_env() {
  umask 077
  {
    echo "# Generated by deploy/lite/init.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) from .env.example. Keep it secret."
    while IFS= read -r line || [ -n "$line" ]; do
      if printf '%s\n' "$line" | grep -Eq "$KEY_PATTERN"; then
        key=${line%%=*}
        echo "$key=$(resolve_value "$key" "${line#*=}")"
      else
        printf '%s\n' "$line"
      fi
    done <"$TEMPLATE"
  } >"$ENV_FILE.tmp"
  mv "$ENV_FILE.tmp" "$ENV_FILE"
  echo "init.sh: created $ENV_FILE"
}

append_missing() {
  grep -E "$KEY_PATTERN" "$TEMPLATE" | while IFS= read -r line; do
    key=${line%%=*}
    if ! has_key "$key"; then
      echo "$key=$(resolve_value "$key" "${line#*=}")" >>"$ENV_FILE"
      echo "init.sh: added missing $key"
    fi
  done
}

report_mode_conflicts() {
  if [ "$mode" = "trial" ] && grep -q "^ROUTER_ENV=$PRODUCTION_ENV\$" "$ENV_FILE"; then
    echo "init.sh: kept existing ROUTER_ENV=$PRODUCTION_ENV (--trial only applies to new keys; edit $ENV_FILE)" >&2
  fi
  if [ "$metrics" = "on" ] && ! grep -q "^COMPOSE_PROFILES=.*$METRICS_PROFILE" "$ENV_FILE"; then
    echo "init.sh: kept existing COMPOSE_PROFILES (--metrics only applies to new keys; edit $ENV_FILE)" >&2
  fi
}

print_summary() {
  echo "init.sh: $ENV_FILE is ready (mode $ENV_FILE_MODE). Back it up: it holds ROUTER_SECRETS_MASTER_KEY."
  if [ -n "$generated_admin_password" ]; then
    echo "init.sh: first-login admin: $(grep '^ROUTER_BOOTSTRAP_ADMIN_EMAIL=' "$ENV_FILE" | cut -d= -f2-)"
    echo "init.sh: first-login password (shown once, change it at first login): $generated_admin_password"
  fi
  echo "init.sh: next: docker compose up -d --build   (from $SCRIPT_DIR)"
}

main() {
  parse_args "$@"
  [ -f "$TEMPLATE" ] || die "template $TEMPLATE not found"
  prepare_inputs
  prepare_admin_password
  if [ -f "$ENV_FILE" ]; then
    append_missing
    report_mode_conflicts
  else
    mkdir -p "$(dirname -- "$ENV_FILE")"
    create_env
  fi
  chmod "$ENV_FILE_MODE" "$ENV_FILE"
  print_summary
}

main "$@"
